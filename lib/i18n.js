    stat: (s, fb) => (en ? EN.stat[s] : null) ?? fb,
    hair: (id, fb) => (en ? EN.hair[id] : null) ?? fb,
    weapon: (id, fb) => (en ? EN.weapon[id] : null) ?? fb,
    skillName: (sk) => (en ? (sk.id === 'basic' ? EN.basic[sk.weapon] : EN.skill[sk.id]?.[0]) : null) ?? sk.name,
    skillDesc: (sk) => (en ? (sk.id === 'basic' ? EN.basicDesc(sk.weapon) : EN.skill[sk.id]?.[1]) : null) ?? sk.desc,
    enemy: (type, fb) => (en ? EN.enemy[type] : null) ?? fb,
    campaignTitle: (id, fb) => (en ? EN.campaign[id]?.[0] : null) ?? fb,
